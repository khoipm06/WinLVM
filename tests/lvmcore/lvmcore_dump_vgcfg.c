/*
 * lvmcore_dump_vgcfg.c — host utility to dump LVM2 volume group metadata
 * from disk images into LVM2 vgcfgbackup format.
 *
 * Usage:
 *   lvmcore_dump_vgcfg <image1> [image2 ...] <output_file>
 *   or
 *   lvmcore_dump_vgcfg -o <output_file> <image1> [image2 ...]
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>
#include <time.h>

#ifdef _WIN32
#define WL_FSEEK64 _fseeki64
#define WL_FTELL64 _ftelli64
#else
#define WL_FSEEK64 fseeko
#define WL_FTELL64 ftello
#endif

#include "lvmcore/types.h"
#include "lvmcore/arena.h"
#include "lvmcore/parser.h"
#include "lvmcore/serialize.h"

#define ARENA_CAP (4u * 1024 * 1024)
static uint8_t arena_buf[ARENA_CAP];
static char text_buf[LVMCORE_MAX_METADATA_BYTES];

static size_t file_read(void *impl, uint64_t offset, void *buf, size_t len) {
    FILE *f = (FILE *)impl;
    if (WL_FSEEK64(f, (int64_t)offset, SEEK_SET) != 0) return 0;
    return fread(buf, 1, len, f);
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: %s <image_file> [image_file2 ...] <output_file>\n", argv[0]);
        fprintf(stderr, "   or: %s -o <output_file> <image_file> [image_file2 ...]\n", argv[0]);
        return 1;
    }

    const char *out_path = NULL;
    const char *in_paths[16];
    size_t in_count = 0;

    if (strcmp(argv[1], "-o") == 0) {
        if (argc < 4) {
            fprintf(stderr, "missing output or input file for -o\n");
            return 1;
        }
        out_path = argv[2];
        for (int i = 3; i < argc && in_count < 16; i++) {
            in_paths[in_count++] = argv[i];
        }
    } else {
        out_path = argv[argc - 1];
        for (int i = 1; i < argc - 1 && in_count < 16; i++) {
            in_paths[in_count++] = argv[i];
        }
    }

    if (!out_path || in_count == 0) {
        fprintf(stderr, "invalid arguments\n");
        return 1;
    }

    FILE *files[16] = {0};
    lvmcore_byte_source srcs[16];
    lvmcore_byte_source *src_ptrs[16];

    for (size_t i = 0; i < in_count; i++) {
        files[i] = fopen(in_paths[i], "rb");
        if (!files[i]) {
            fprintf(stderr, "error: cannot open input image '%s'\n", in_paths[i]);
            for (size_t j = 0; j < i; j++) fclose(files[j]);
            return 1;
        }
        WL_FSEEK64(files[i], 0, SEEK_END);
        uint64_t sz = (uint64_t)WL_FTELL64(files[i]);
        WL_FSEEK64(files[i], 0, SEEK_SET);

        srcs[i].impl = files[i];
        srcs[i].size = sz;
        srcs[i].read = file_read;
        src_ptrs[i] = &srcs[i];
    }

    lvmcore_arena arena;
    lvmcore_arena_init(&arena, arena_buf, sizeof(arena_buf));

    lvmcore_volume_group vg;
    lvmcore_err err;
    memset(&err, 0, sizeof(err));
    lvmcore_status st;

    if (in_count == 1) {
        st = lvmcore_read_vg(src_ptrs[0], LVMCORE_READ_FLAG_DEFAULT, &arena, &vg, &err);
    } else {
        st = lvmcore_read_vg_multi(src_ptrs, in_count, LVMCORE_READ_FLAG_DEFAULT, &arena, &vg, &err);
    }

    for (size_t i = 0; i < in_count; i++) {
        fclose(files[i]);
    }

    if (st != LVMCORE_OK) {
        fprintf(stderr, "error: failed to read VG from input: status=%d message=%s\n",
                (int)st, err.message[0] ? err.message : "unknown");
        return 1;
    }

    size_t ser_len = 0;
    st = lvmcore_serialize_vg(&vg, text_buf, sizeof(text_buf), &ser_len);
    if (st != LVMCORE_OK || ser_len == 0) {
        fprintf(stderr, "error: failed to serialize VG: status=%d\n", (int)st);
        return 1;
    }

    FILE *out = fopen(out_path, "wb");
    if (!out) {
        fprintf(stderr, "error: cannot open output file '%s' for writing\n", out_path);
        return 1;
    }

    time_t now = time(NULL);
    if (now == (time_t)-1) now = 1700000000;

    fprintf(out, "# Generated by winlvm lvmcore_dump_vgcfg\n\n");
    fprintf(out, "contents = \"Text Format Volume Group\"\n");
    fprintf(out, "version = 1\n\n");
    fprintf(out, "description = \"Dumped by winlvm lvmcore_dump_vgcfg for %s\"\n\n", vg.name);
    fprintf(out, "creation_host = \"localhost\"\n");
    fprintf(out, "creation_time = %llu\n\n", (unsigned long long)now);

    /* Write serialized VG block (ser_len includes trailing NUL, we write text only) */
    size_t text_chars = (ser_len > 0 && text_buf[ser_len - 1] == '\0') ? ser_len - 1 : ser_len;
    if (fwrite(text_buf, 1, text_chars, out) != text_chars) {
        fprintf(stderr, "error: failed to write serialized metadata to '%s'\n", out_path);
        fclose(out);
        return 1;
    }

    fclose(out);
    printf("dumped VG '%s' (seqno %llu, %zu PVs, %zu LVs) to '%s'\n",
           vg.name, (unsigned long long)vg.seqno, vg.pv_count, vg.lv_count, out_path);
    return 0;
}
